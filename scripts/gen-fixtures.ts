/** Generates fixtures/*.csv and fixtures/expected/*.json deterministically. Run: npm run fixtures */
import { mkdirSync, writeFileSync } from "node:fs";
import { BRANDS, STRAINS, VENDORS, seedCatalog } from "@distru/csv-importer/distru";
import { productSchema } from "@distru/csv-importer/distru";
import { toCsv } from "@distru/csv-importer/core";

let seed = 42;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
const pick = <T,>(a: T[]) => a[Math.floor(rnd() * a.length)];
const money = (n: number) => n.toFixed(2);

mkdirSync("fixtures/expected", { recursive: true });
const write = (name: string, headers: string[], rows: Record<string, string>[], expected: Record<string, string | null>, prefix = "") => {
  writeFileSync(`fixtures/${name}.csv`, prefix + toCsv(headers, rows));
  writeFileSync(`fixtures/expected/${name}.json`, JSON.stringify(expected, null, 2) + "\n");
};

const TYPES = [
  { label: "3.5g", cat: "Flower", w: "3.5g", price: 35 },
  { label: "7g", cat: "Flower", w: "7g", price: 60 },
  { label: "Pre-Roll 1g", cat: "Pre-Roll", w: "1g", price: 12 },
  { label: "Live Resin Cart 0.5g", cat: "Vape", w: "0.5g", price: 40 },
  { label: "Gummies 10pk", cat: "Edible", w: "10 x 10mg", price: 20 },
];

// 1. clean: friendly headers, 100 new products.
{
  const headers = ["Product Name", "SKU", "Category", "Strain", "Brand", "Vendor", "Price", "Cost", "Weight", "THC %", "Barcode", "Description"];
  const rows = Array.from({ length: 100 }, (_, i) => {
    const t = TYPES[i % TYPES.length];
    const strain = STRAINS[i % STRAINS.length];
    return {
      "Product Name": `${strain} ${t.label}`, SKU: `CL-${1000 + i}`, Category: t.cat, Strain: strain, Brand: pick(BRANDS), Vendor: pick(VENDORS),
      Price: money(t.price), Cost: money(t.price * 0.45), Weight: t.w.includes("mg") ? "" : t.w, "THC %": `${(18 + rnd() * 12).toFixed(1)}%`,
      Barcode: String(860000000000 + i), Description: `${strain} by the house team`,
    };
  });
  write("clean-100", headers, rows, {
    "Product Name": "name", SKU: "sku", Category: "category", Strain: "strain", Brand: "brand", Vendor: "vendor", Price: "unit_price",
    Cost: "unit_cost", Weight: "net_weight", "THC %": "total_thc", Barcode: "upc", Description: "description",
  });
}

// 2. messy: title rows above the header, odd headers, errors, blank lines, a totals row.
{
  const headers = ["Item Title", "Item #", "Retail ($)", "Landed Cost", "Size", "THC", "Cultivar", "Mfr", "Supplier", "Status", "Notes", "Internal Ref"];
  const rows: Record<string, string>[] = [];
  for (let i = 0; i < 200; i++) {
    const t = TYPES[i % TYPES.length];
    const strain = STRAINS[(i * 7) % STRAINS.length];
    const r: Record<string, string> = {
      "Item Title": `${strain} ${t.label}`, "Item #": `MS-${2000 + i}`, "Retail ($)": `$${money(t.price)}`, "Landed Cost": money(t.price * 0.5),
      Size: t.w.includes("mg") ? "" : t.w, THC: `${(15 + rnd() * 15).toFixed(1)}%`, Cultivar: strain, Mfr: pick(BRANDS), Supplier: pick(VENDORS),
      Status: pick(["Active", "Active", "Active", "Inactive"]), Notes: "", "Internal Ref": `X${i}`,
    };
    if (i % 23 === 5) r["Item Title"] = "";                       // missing name -> invalid
    if (i % 31 === 7) r["Retail ($)"] = `€${money(t.price)}`;     // non-default currency -> invalid
    if (i % 29 === 3) r.Supplier = "Unknown Farms";                // must-exist vendor not in Distru
    if (i % 37 === 11) r["Item #"] = "1.23E+11";                   // scientific notation SKU (warning)
    if (i % 41 === 13) r["Item #"] = `MS-${2000 + i - 1}`;         // duplicate SKU in file
    if (i % 17 === 9) r.Size = pick(["eighth", "quarter", "half"]); // slang, confirmed at Gate 1
    rows.push(r);
    if (i % 50 === 49) rows.push(Object.fromEntries(headers.map((h) => [h, ""])));
  }
  rows.push({ ...Object.fromEntries(headers.map((h) => [h, ""])), "Item Title": "TOTAL", "Retail ($)": "$6,000.00" });
  write("messy-200", headers, rows, {
    "Item Title": "name", "Item #": "sku", "Retail ($)": "unit_price", "Landed Cost": "unit_cost", Size: "net_weight", THC: "total_thc",
    Cultivar: "strain", Mfr: "brand", Supplier: "vendor", Status: "active", Notes: null, "Internal Ref": null,
  }, "Spring catalog export\nGenerated by POS v2,,,,,,,,,,,\n");
}

// 3. duplicate-heavy: overlaps the 50-product mock catalog.
{
  const catalog = seedCatalog();
  const headers = ["Name", "SKU", "Unit Price", "Category", "Brand"];
  const rows: Record<string, string>[] = [];
  catalog.slice(0, 30).forEach((p) => rows.push({ Name: p.name, SKU: p.sku!, "Unit Price": money(p.unitPrice!), Category: p.category!.name, Brand: p.brand!.name }));
  catalog.slice(30, 45).forEach((p) => rows.push({ Name: p.name, SKU: p.sku!, "Unit Price": money(p.unitPrice! + 5), Category: p.category!.name, Brand: p.brand!.name }));
  rows.slice(0, 10).forEach((r) => rows.push({ ...r }));
  for (let i = 0; i < 20; i++) rows.push({ Name: `New Strain ${i} 3.5g`, SKU: `NEW-${i}`, "Unit Price": "35.00", Category: "Flower", Brand: pick(BRANDS) });
  write("duplicate-heavy", headers, rows, { Name: "name", SKU: "sku", "Unit Price": "unit_price", Category: "category", Brand: "brand" });
}

// 4. template-exact: Distru's own template headers.
{
  const headers = productSchema.templateHeaders;
  const rows = Array.from({ length: 50 }, (_, i) => {
    const strain = STRAINS[i % STRAINS.length];
    const r: Record<string, string> = Object.fromEntries(headers.map((h) => [h, ""]));
    Object.assign(r, {
      Name: `${strain} Smalls 14g`, SKU: `TPL-${i}`, "Product Category": "Flower", Strain: strain, Brand: pick(BRANDS), Vendor: pick(VENDORS),
      "Unit Type Name": "Gram", "Tracking Method": "batch", "Unit Price": "90", "Unit Cost": "40", "Net Quantity per Unit": "14", Inactive: "FALSE",
    });
    return r;
  });
  const expected: Record<string, string> = {};
  for (const h of headers) expected[h] = Object.values(productSchema.fields).find((f) => f.header === h)!.name;
  write("template-exact", headers, rows, expected);
}

